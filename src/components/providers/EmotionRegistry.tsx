'use client';

import { useState, type ReactNode } from 'react';
import { useServerInsertedHTML } from 'next/navigation';
import createCache from '@emotion/cache';
import { CacheProvider } from '@emotion/react';

interface EmotionRegistryProps {
  children: ReactNode;
}

interface InsertedStyle {
  name: string;
  isGlobal: boolean;
}

function createRegistry() {
  const cache = createCache({ key: 'css' });
  cache.compat = true;
  const insert = cache.insert;
  let pending: InsertedStyle[] = [];

  cache.insert = (selector, serialized, sheet, shouldCache) => {
    if (cache.inserted[serialized.name] === undefined) {
      pending.push({ name: serialized.name, isGlobal: selector === '' });
    }
    return insert(selector, serialized, sheet, shouldCache);
  };

  function flush() {
    const flushed = pending;
    pending = [];
    return flushed;
  }

  return { cache, flush };
}

/**
 * Collects Emotion styles during server rendering and emits them in the
 * document head, so the streamed HTML matches the client on hydration.
 * The injected CSS is generated by Emotion from our own theme, never from
 * user input.
 */
export function EmotionRegistry({ children }: EmotionRegistryProps) {
  const [{ cache, flush }] = useState(createRegistry);

  useServerInsertedHTML(() => {
    const inserted = flush();
    if (inserted.length === 0) return null;

    const globals: { name: string; css: string }[] = [];
    let scopedCss = '';
    let scopedNames = '';

    for (const { name, isGlobal } of inserted) {
      const css = cache.inserted[name];
      if (typeof css !== 'string') continue;
      if (isGlobal) {
        globals.push({ name, css });
      } else {
        scopedCss += css;
        scopedNames += ` ${name}`;
      }
    }

    return (
      <>
        {globals.map(({ name, css }) => (
          <style
            key={name}
            data-emotion={`${cache.key}-global ${name}`}
            dangerouslySetInnerHTML={{ __html: css }}
          />
        ))}
        {scopedCss && (
          <style
            data-emotion={`${cache.key}${scopedNames}`}
            dangerouslySetInnerHTML={{ __html: scopedCss }}
          />
        )}
      </>
    );
  });

  return <CacheProvider value={cache}>{children}</CacheProvider>;
}
